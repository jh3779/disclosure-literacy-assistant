"""LLM이 만든 사실 문장에 투자 조언 표현이 섞였는지 결정적으로 검사한다 — 규제 방어선.

**왜 필요한가**(2026-09-22 규제 방어선 점검 F1): `verify.py`의 1차 추출 프롬프트는
"매수매도 의견·목표가는 절대 출력하지 않는다"고 지시하지만, 2차 guard 프롬프트는
근거성·관련성만 검사하고 **투자 판단 표현은 검사하지 않는다.** 그 뒤에 코드로 거르는
장치도 없었다 — 가장 위험한 동적 텍스트(LLM 출력)가 확률적 방어(프롬프트 지시) 하나에만
기대고 있었다. 반대로 사람이 쓰고 검토하는 정적 텍스트인 용어 사전은
`dictionary/glossary.py::_BANNED_WORDS`로 코드 검사를 받고 있었다.

**경계를 이렇게 좁게 잡은 이유 — 실측**(코퍼스 82,876개 섹션 전수 검사):
처음 후보 11개 중 8개가 **정상 공시 원문에 대량으로** 등장했다. LLM이 원문을 충실히
요약하면 그 표현이 그대로 들어오므로, 그런 패턴을 막으면 정상 사실까지 지워진다.

- `목표가` 62회 — "당기순이익 **목표가** 450억원이었으나"(목표 + 조사 "가")
- `고평가` 579회 — "재**고평가**충당금"(재고평가의 일부)
- `호재` 243회 — "제이더블유이종**호재**단"(이종호 + 재단)
- `기대수익률` 181회 — "사외적립자산의 기대수익률"(퇴직연금 회계 용어)
- `목표주가` 16회 — "**목표주가**와 같은 시장조건"(주식보상 회계, IFRS 2)
- `적정주가` 40회 — 자기주식 취득 목적 "적정주가 확보"
- `매수시점` 159회 — "매수시점의 공정가치"(사업결합 회계)
- `주가가 하락할 가능성` 75회 — **증권신고서의 법정 투자위험 고지**

마지막 항목이 특히 중요하다 — 이걸 막으면 **부정적 사실만 골라 지우게 되어**
"긍정/부정 동일 비중"(03-integrated-proposal.md 7절) 방어선을 오히려 깨뜨린다.

그래서 이 모듈은 **"시스템이 투자 조언을 하는 발화"**로만 경계를 긋는다. 회사는 공시에서
자기 주식을 사라거나 팔라고 권하지 않으므로, 이 표현들은 원문에 **0회**다 — LLM 출력에
나타났다면 원문 요약이 아니라 LLM이 만들어낸 것이다.

**2026-09-22 v2 — 팀 리뷰(@9abin)로 드러난 누락 보강**: v1은 "매수 적기"처럼 조사 없는
형태만 잡아, **자연스러운 권유 문장의 대부분을 놓쳤다.** 변형을 체계적으로 생성해 재보니
서술형 240개 중 36개(15%), 명령·청유형 22개 중 6개(27%)만 적중했다 — "결정적 방어선"이라
부를 수준이 아니었다. 원인은 두 가지다.

- 목적격 조사가 끼면 안 잡힘: `매수\\s*추천` 은 "매수**를** 추천"을 못 잡는다
- 어미를 하드코딩(`하세요|하십시오|해야 합니다`)해서 "하시기 바랍니다", "권장드립니다"
  같은 흔한 변형이 전부 빠졌다

그래서 **어미를 열어두고**(조언 명사까지만 매칭) **조사를 허용**하도록 바꿨다. 넓힌 패턴도
전부 코퍼스 전수 재측정으로 0회를 확인했다.

**일부러 막지 않는 것**(측정·리뷰 근거로 제외):

- `매수/매도 신호`, 띄어 쓴 `투자 의견` — 시스템의 조언이 아니라 **공시 내용을 서술**하는
  문장일 수 있다("기술적 지표상 매수 신호가 발생했다고 밝혔다", "주주들의 투자 의견을
  수렴하였다"). 코퍼스 등장은 0회지만 `의견을 수렴`은 545회 나와 형태 자체는 현실적이다.
  붙여 쓴 `투자의견`(증권가 용어)만 막는다.
- `투자를 추천/권유` — **2,125회** 등장. 신용평가 고지문의 정형구다("특정 회사채에 대한
  투자를 추천하거나 원리금 상환을 보증하는 것이 아니며…"). 막으면 정상 사실이 대량 삭제된다.
- `강력추천`(21회, 제품 리뷰 "Highly Recommended" 번역), `종목추천`(20회, 증권사 랩어카운트
  서비스 설명), `목표주가`(16회), `적정주가`(40회), `매수시점`(159회).

**2026-09-24 v3 — 리뷰로 드러난 누락·오탐 보강**:

- 누락: v2도 명사화 연결형("매수**하는 것을** 추천", "매도**할 것을** 권고")과 동사
  "권하다"("매수를 **권합니다**")를 놓쳤다. 행위×연결형×조언어 조합 150개 중 82개가
  빠졌다. 연결형 목록과 `권하다`를 추가했다.
- 오탐: "해당 회사채의 매수를 추천하는 것이 **아니다**"처럼 조언을 **부정하는** 고지문도
  걸렸다. 원문에는 "투자를 추천"으로 나오지만(위 2,125회) LLM이 요약하며 "매수를
  추천"으로 바꿔 쓰면 매칭된다 — **원문 0회는 요약문 오탐까지 막아주지 못한다.** 그래서
  조언 행위(A군) 바로 뒤에 붙는 고지문식 부정("~하는 것이 아니다", "~이 아니다",
  "~하거나 …하는 것이 아니다")은 제외한다. 반면 "추천하지 **않습니다**"는 시스템의
  의견(비추천)이라 계속 잡는다 — 부정 판정은 명사화된 고지문 형태로만 좁혔다.
- 재측정(릴리즈 `corpus-snapshot-2026-09-16`, 82,876섹션·약 480만 문장): v3도 원문 적중
  0회다. 새 연결형 자체는 원문에 흔하지만("매수할 것을 조건으로" 53회, "매수할 것을
  결의하였으며" 38회, "매수할 것을 청구할" 22회 등) 뒤에 조언어가 오지 않아 걸리지
  않는다. 고지문 부정으로 제외된 원문 매칭도 0회다 — 원문 고지문은 "투자를 추천"(A군
  밖)이라, 이 제외 규칙은 LLM이 바꿔 쓴 요약문에서만 작동한다.

**이 필터가 못 막는 것**: "실적 개선이 기대된다"처럼 출처 없이 쓴 미래 전망. 원문에도
"회사는 ~를 기대한다" 형태로 흔히 나오고, 위의 투자위험 고지처럼 막으면 안 되는 문장과
정규식으로 구분할 수 없다. 이건 문맥 판단이 필요해 LLM guard 쪽에서 다뤄야 한다.

**패턴을 넓히기 전에**: 반드시 코퍼스 전수 검사로 원문 등장 횟수를 다시 재고, 0회가
아니면 추가하지 않는다. 테스트가 양방향을 모두 고정한다 —
`_LEGITIMATE_DISCLOSURE_PHRASES`(실측 오탐 사례)와 조사·어미 변형 격자(누락).
"""

from __future__ import annotations

import re

# 전부 코퍼스 82,876개 섹션에서 원문 등장 0회로 실측된 패턴이다(모듈 docstring).
_INVESTMENT_ADVICE = re.compile(
    # A. 조언 행위 — 조사·명사화 연결형이 끼어도, 어미가 무엇이든 잡는다("매수를
    #    추천합니다", "매수하는 것을 권고합니다"). "권"은 "권하다" 활용형일 때만 —
    #    "매수 권한"(권한=authority)은 잡지 않는다.
    r"(?P<act>(?:매수|매도)\s*"
    r"(?:를|을|하기를|하시기를|하길|하는\s*것을|하는\s*걸|할\s*것을|할\s*걸"
    r"|하시는\s*것을|하시는\s*걸|하실\s*것을|하기)?"
    r"\s*(?:추천|권유|권고|권장|권(?=하|합|해|함|할)))"
    # B. 명령·청유형
    r"|(?:매수|매도)\s*(?:하세요|하십시오|하시기\s*바랍|하시길|하시는\s*것을"
    r"|해야\s*합니다|합시다|하시죠|하기\s*바랍|할\s*때입니다|하실\s*타이밍"
    r"|하시기\s*권|해보세요)"
    r"|사세요|파세요|사시기\s*바랍|파시기\s*바랍"
    # C. 매매 시점을 권하는 명사
    r"|(?:매수|매도)\s*(?:적기|타이밍)"
    # D. 증권가 투자의견 용어와 그 등급 표현. **"투자의견"은 붙여 쓴 형태만** —
    #    띄어 쓴 "투자 의견"은 서술일 수 있다(아래 "일부러 막지 않는 것" 참고).
    r"|투자의견"
    r"|비중\s*(?:확대|축소)\s*의견"
    # E. 증권가 등급 표현(2026-09-24 자체 리뷰로 드러난 누락). D의 "투자의견"과 같은
    #    성격인데 빠져 있었다 — LLM이 "매수의견을 제시했다"로 요약할 개연성은
    #    "추천한다"보다 낮지 않다. 띄어 쓴 형태까지 막는 이유: "투자 의견"과 달리
    #    이 조합들은 **띄어쓰기 여부와 무관하게 전부 실코퍼스 0회**다
    #    (`scripts/measure_corpus_terms.py`로 재측정, 82,876섹션).
    #    단 "공개매수"(tender offer)는 뺀다 — 원문 "공개매수에 찬동한다는 의견을 표명"
    #    (14회)을 LLM이 "공개매수 의견을 표명"으로 줄이면 조언이 아닌데 걸린다.
    r"|(?:(?<!공개)매수|매도|보유)\s*(?:의견|등급)"
    r"|(?:(?<!공개)매수|매도)\s*기회"
)


# 매칭 전에 걷어내는 문자 — 강조 마크다운과 보이지 않는 문자.
#
# 화면이 `st.markdown(f"- {item.fact}")`로 렌더링하므로 LLM이 강조를 넣는 건 자연스러운
# 일이다. 실제로 `"**매수**를 추천합니다"`가 패턴을 그대로 통과했다 — 악의적 우회가
# 아니라 평범하게 일어날 수 있는 경우다. zero-width 문자는 모델 출력이나 복사·붙여넣기에
# 섞여 들어오는 경우를 대비한다.
#
# 이것도 "넓히는 변경"이라 코퍼스 전수로 먼저 쟀다 — 정규화한 82,876개 섹션에 최종
# 정규식을 돌려 **적중 0건**을 확인했다(`_`를 지워 "전환사채_발행" 같은 유형명이 붙어도
# 새로 걸리는 것은 없었다).
_MATCH_NOISE = re.compile(r"[*_`~​‌‍﻿]")


# "추천은 아니지만 …"은 뒤에 평가를 잇는 헤지 화법이라 부정으로 치지 않는다.
_NEGATION = r"(?:아니(?!지만)|아닙|아님|아닌)"
_DISCLAIMER_CLAUSE = (
    r"(?:하는|하려는|한|드리는|드리려는|드린|하기\s*위한)\s*(?:것|바|취지|목적)"
    r"(?:이|가|은|는|도)?\s*" + _NEGATION
)
# A군 매칭 직후에 붙는 고지문식 부정(모듈 docstring v3). "~하거나/또는 …" 뒤의 부정은
# 같은 문장 안 40자까지만 본다 — 신용평가 고지문 "추천하거나 원리금 상환을 보증하는
# 것이 아니며"가 이 형태다.
_NEGATED_DISCLAIMER = re.compile(
    r"\s*(?:"
    + _DISCLAIMER_CLAUSE
    + r"|(?:이|가|은|는|도)?\s*"
    + _NEGATION
    + r"|(?:하거나|이거나|이나|또는|및)[^.?!\n]{0,40}?(?:"
    + _DISCLAIMER_CLAUSE
    + r"|(?:이|가)\s*"
    + _NEGATION
    + r"))"
)


def find_investment_advice(text: str) -> str | None:
    """`text`에서 투자 조언 표현을 찾으면 그 부분을, 없으면 None을 반환한다.

    강조 마크다운·보이지 않는 문자를 걷어낸 사본에서 찾는다(`_MATCH_NOISE`). 반환값은
    그 사본에서 잘라낸 것이라 원문과 글자가 다를 수 있다 — 로그·진단용이며, 화면에
    나가는 텍스트를 이 함수가 바꾸지는 않는다. 고지문식 부정 판정도 같은 사본에서 한다
    ("**추천**하는 것이 아니다"가 강조 때문에 부정으로 안 잡히면 안 된다).
    """
    normalized = _MATCH_NOISE.sub("", text)
    for match in _INVESTMENT_ADVICE.finditer(normalized):
        if match.group("act") and _NEGATED_DISCLAIMER.match(normalized, match.end()):
            continue
        return match.group(0)
    return None
